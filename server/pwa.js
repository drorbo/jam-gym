// The installable-app side of the site: the list of files the service worker keeps for offline use, and the worker itself.
// The worker is generated (not a static file) because its list has to name the fingerprinted "?v=" addresses the page loads.

import { createHash } from 'node:crypto';
import { readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

/** Every file under `dir`, as a URL path ("/samples/keys/piano/a.wav") with its size, sorted so the result is stable. */
export function listFiles(base, dir) {
  const out = [];
  const walk = (d) => {
    for (const entry of readdirSync(d, { withFileTypes: true })) {
      const full = join(d, entry.name);
      if (entry.isDirectory()) walk(full);
      else out.push({ url: `/${relative(base, full).split(sep).join('/')}`, size: statSync(full).size });
    }
  };
  try { walk(join(base, dir)); } catch { /* a missing folder just means nothing to keep */ }
  return out.sort((a, b) => (a.url < b.url ? -1 : 1));
}

function hash(text) { return createHash('sha256').update(text).digest('hex').slice(0, 10); }

/**
 * What the worker keeps. `shell` is everything needed to start the app (the page, versioned scripts and styles, fonts,
 * icons, the manifest); `samples` is the recorded sounds, which are bigger and downloaded in the background.
 * @param {Map<string,string>} versions fingerprints() of the scripts and styles
 */
export function precacheLists(base, versions) {
  const shell = ['/', '/manifest.webmanifest'];
  for (const [path, v] of versions) shell.push(`${path}?v=${v}`);
  for (const f of listFiles(base, 'fonts')) shell.push(f.url);
  for (const f of listFiles(base, 'icons')) shell.push(f.url);
  const samples = listFiles(base, 'samples').filter((f) => f.url.endsWith('.wav') || f.url.endsWith('.json'));
  return {
    shell,
    samples: samples.map((f) => f.url),
    samplesTag: hash(samples.map((f) => `${f.url}:${f.size}`).join('\n')),
  };
}

/** The text of /sw.js. `tag` changes whenever the page or any script or style does, so a deploy installs a fresh worker. */
export function buildServiceWorker({ shell, samples, samplesTag }, tag) {
  return `// Jam Gym service worker (generated by server/pwa.js). Keeps the app and its sounds for offline use.
const SHELL = 'jg-shell-${tag}';
const SAMPLES = 'jg-samples-${samplesTag}';
const SHELL_URLS = ${JSON.stringify(shell)};
const SAMPLE_URLS = ${JSON.stringify(samples)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL).then((cache) => cache.addAll(SHELL_URLS)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      const stale = (key.startsWith('jg-shell-') && key !== SHELL) || (key.startsWith('jg-samples-') && key !== SAMPLES);
      if (stale) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});

const shellHrefs = new Set(SHELL_URLS.map((u) => new URL(u, self.location.origin).href));

/** Network first, but give up after a few seconds so a bad connection still opens the saved copy. */
function networkFirst(request, cache, key, ms) {
  return new Promise((resolve) => {
    let settled = false;
    const fallback = async () => (await cache.match(key, { ignoreSearch: true })) || Response.error();
    const timer = setTimeout(async () => { if (!settled) { settled = true; resolve(await fallback()); } }, ms);
    fetch(request).then(async (res) => {
      if (settled) return;
      settled = true; clearTimeout(timer);
      if (res.ok) cache.put(key, res.clone());
      resolve(res);
    }, async () => {
      if (settled) return;
      settled = true; clearTimeout(timer);
      resolve(await fallback());
    });
  });
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || request.headers.has('range')) return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  // the account and tracks API is never kept: the app handles being offline itself
  if (url.pathname === '/api' || url.pathname.startsWith('/api/') || url.pathname === '/sw.js') return;

  if (request.mode === 'navigate') {
    event.respondWith(caches.open(SHELL).then((cache) => networkFirst(request, cache, '/', 4000)));
  } else if (url.pathname.startsWith('/samples/')) {
    event.respondWith((async () => {
      const cache = await caches.open(SAMPLES);
      const hit = await cache.match(request);
      if (hit) return hit;
      const res = await fetch(request);
      if (res.ok) cache.put(request, res.clone());
      return res;
    })());
  } else if (shellHrefs.has(url.href) || url.pathname.startsWith('/fonts/') || url.pathname.startsWith('/icons/')) {
    event.respondWith((async () => {
      const hit = await (await caches.open(SHELL)).match(request);
      return hit || fetch(request);
    })());
  }
});

// The page asks for the sounds to be kept too, so every instrument works offline. Files already kept are skipped, so
// asking again is cheap, and a file that fails is just left for next time.
async function keepSamples() {
  const cache = await caches.open(SAMPLES);
  const todo = [];
  for (const u of SAMPLE_URLS) if (!(await cache.match(u))) todo.push(u);
  const total = SAMPLE_URLS.length;
  let done = total - todo.length;
  const tell = async (state) => {
    for (const c of await self.clients.matchAll()) c.postMessage({ type: 'offline-progress', done, total, state });
  };
  await tell('working');
  const next = async () => {
    while (todo.length) {
      const u = todo.shift();
      try {
        const res = await fetch(u);
        if (res.ok) { await cache.put(u, res); done++; }
      } catch { /* try again next time */ }
      if (done % 10 === 0) await tell('working');
    }
  };
  await Promise.all([next(), next(), next(), next()]);
  await tell(done >= total ? 'ready' : 'partial');
}

let keeping = null;
self.addEventListener('message', (event) => {
  const type = event.data && event.data.type;
  if (type === 'keep-samples' && !keeping) {
    keeping = keepSamples().finally(() => { keeping = null; });
    event.waitUntil(keeping);
  } else if (type === 'status') {
    const source = event.source;
    event.waitUntil(caches.open(SAMPLES).then(async (cache) => {
      let done = 0;
      for (const u of SAMPLE_URLS) if (await cache.match(u)) done++;
      const state = done >= SAMPLE_URLS.length ? 'ready' : 'idle';
      if (source) source.postMessage({ type: 'offline-progress', done, total: SAMPLE_URLS.length, state });
    }));
  }
});
`;
}
